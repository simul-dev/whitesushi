import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { evaluate, type PolicyScore } from "./evaluate";
import { BASELINES } from "./baselines";
import { optimize } from "./optimize";
import { DEV_SEEDS, SCENARIOS, TEST_SEEDS } from "./scenarios";
import { describeProblem } from "./describe";

const [command, ...rest] = process.argv.slice(2);
const flag = (name: string, fallback?: string) => { const i = rest.indexOf(`--${name}`); return i >= 0 ? rest[i + 1] : fallback; };
const seedsFor = (split: string) => split === "test" ? TEST_SEEDS : split === "dev" ? DEV_SEEDS : (() => { throw new Error("--split is dev or test"); })();
const won = (v: number) => `${(v / 10000).toFixed(1)}만`;
const write = (path: string, text: string) => { mkdirSync(dirname(resolve(path)), { recursive: true }); writeFileSync(path, text); };

function table(scores: PolicyScore[]) {
  const rows = scores.map(s => {
    const cell = (id: string) => { const x = s.scenarios.find(r => r.scenario === id)!; return `${won(x.profit)}${x.violations.length ? " ✗" : ""}`; };
    return `| ${s.policy} | ${s.feasible ? "yes" : "no"} | ${won(s.total)} | ${SCENARIOS.map(sc => cell(sc.id)).join(" | ")} |`;
  });
  return [`| policy | meets service levels | total daily profit (KRW) | ${SCENARIOS.map(s => s.id).join(" | ")} |`, `|---|---|---|${SCENARIOS.map(() => "---").join("|")}|`, ...rows].join("\n");
}
function detail(s: PolicyScore) {
  return s.scenarios.map(x => `  ${x.scenario.padEnd(14)} profit ${won(x.profit)} ±${won(x.profitStdErr)}  labor ${won(x.labor)}  hall lost ${(x.dineInLostRate * 100).toFixed(1)}%  hall p90 wait ${Math.round(x.dineInP90WaitSeconds)}s  delivery lost ${(x.deliveryLostRate * 100).toFixed(1)}%  delivery p90 kitchen wait ${Math.round(x.deliveryP90KitchenWaitSeconds)}s  cooks busy ${(x.cookUtilization * 100).toFixed(0)}%${x.violations.length ? `\n${"".padEnd(17)}✗ ${x.violations.join("; ")}` : ""}`).join("\n");
}
const rank = (scores: PolicyScore[]) => [...scores].sort((a, b) => Number(b.feasible) - Number(a.feasible) || b.total - a.total);

if (command === "describe") console.log(describeProblem());
else if (command === "eval") {
  const file = rest.find(arg => !arg.startsWith("--") && arg !== flag("split") && arg !== flag("json"));
  if (!file) throw new Error("usage: bench eval <policy.json> [--split dev|test] [--json out.json]");
  const split = flag("split", "dev")!;
  const score = await evaluate(JSON.parse(readFileSync(file, "utf8")), seedsFor(split), split);
  console.log(`${score.policy} (${split} seeds): ${score.feasible ? "meets all service levels" : "VIOLATES service levels"}, total ${won(score.total)} KRW/day\n${detail(score)}`);
  if (flag("json")) write(flag("json")!, JSON.stringify(score, null, 2));
} else if (command === "optimize") {
  const { policy } = await optimize(BASELINES[3], DEV_SEEDS, { margin: Number(flag("margin", "0.9")), log: console.log });
  write(flag("out", "bench/policies/sim-search.json")!, JSON.stringify(policy, null, 2) + "\n");
  console.log(`wrote ${flag("out", "bench/policies/sim-search.json")}`);
} else if (command === "leaderboard") {
  // Scores every policy file on the test seeds and rewrites the leaderboard.
  const files = rest.filter(arg => arg.endsWith(".json"));
  const policies = [...BASELINES, ...files.map(f => JSON.parse(readFileSync(f, "utf8")))];
  const scores: PolicyScore[] = [];
  for (const policy of policies) { const s = await evaluate(policy, TEST_SEEDS, "test"); scores.push(s); console.log(`${s.policy}: ${s.feasible ? "ok" : "violates"} ${won(s.total)}`); }
  write("bench/results/leaderboard.json", JSON.stringify(rank(scores), null, 2) + "\n");
  write("bench/results/leaderboard.md", `# Leaderboard (test seeds ${TEST_SEEDS[0]}-${TEST_SEEDS.at(-1)}, ${TEST_SEEDS.length} replications per scenario)\n\nGenerated by \`npm run bench -- leaderboard\`. ✗ = that scenario misses a service level. Policies that miss any service level rank below all that meet them.\n\n${table(rank(scores))}\n\n## Detail\n\n${rank(scores).map(s => `### ${s.policy}\n\n\`\`\`\n${detail(s)}\n\`\`\``).join("\n\n")}\n`);
  console.log("wrote bench/results/leaderboard.md");
} else {
  console.log("usage: npm run bench -- <describe | eval <policy.json> [--split dev|test] | optimize [--margin 0.9] | leaderboard [extra policies...]>");
}
